#!/usr/bin/env node
/**
 * The quiet sound effects under the full canto readings. They are not mixed into the narration MP3s: the page
 * plays them alongside, from the plan in data/narration-effects.json, so they can be switched off and a canto's
 * recording never has to be rebuilt for them.
 *
 *   node tools/audio/effects.mjs                       check every canto's plan against its live word timings
 *   node tools/audio/effects.mjs --only inferno:1      check and list one canto's sounds with their times
 *   node tools/audio/effects.mjs --file drafts.json    check a draft file of plans without touching the data
 *   node tools/audio/effects.mjs --sounds              copy the sounds into public/audio-effects/ and record their loudness
 *
 * The sounds themselves are generated by tools/audio/summaries.mjs from the prompts in data/summary-effects.json
 * into scripts/narrations_v4/sfx/. Nothing here spends credits.
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { OUT_DIR, ROOT, readJson } from './lib.mjs';
import { resolvePlan } from '../../src/lib/narration-effects-resolve.mjs';

const DATA = path.join(ROOT, 'data', 'narration-effects.json');
const SFX = path.join(OUT_DIR, 'sfx');
const LIVE = path.join(ROOT, 'public', 'audio-effects');
// A background shorter than this is a sign of a plan that changes too often to stay in the background
const SHORT_BED = 25;

const args = process.argv.slice(2);
const valueOf = flag => (args.includes(flag) ? args[args.indexOf(flag) + 1] : null);
const data = readJson(DATA);

/** Integrated loudness of a file, in LUFS */
function loudness(file) {
  const out = spawnSync('ffmpeg', ['-hide_banner', '-nostats', '-i', file, '-af', 'ebur128', '-f', 'null', '-'], { encoding: 'utf8' }).stderr;
  const found = out.match(/Integrated loudness:\s+I:\s+(-?[\d.]+) LUFS/);
  if (!found) throw new Error(`No loudness for ${file}`);
  return parseFloat(found[1]);
}

if (args.includes('--sounds')) {
  const prompts = readJson(path.join(ROOT, 'data', 'summary-effects.json')).sounds;
  fs.mkdirSync(LIVE, { recursive: true });
  const used = new Set(Object.values(data.cantos).flat().map(e => e.bed ?? e.cue).filter(Boolean));
  for (const [name, { loop }] of Object.entries(prompts)) {
    const source = path.join(SFX, `${name}.mp3`);
    if (!fs.existsSync(source)) {
      console.log(`${name}: not generated yet`);
      continue;
    }
    data.sounds[name] = { loop: !!loop, lufs: loudness(source) };
    const live = path.join(LIVE, `${name}.mp3`);
    if (used.has(name)) fs.copyFileSync(source, live);
    else fs.rmSync(live, { force: true });
    console.log(`${name}: ${data.sounds[name].lufs} LUFS${used.has(name) ? '' : ' (not used by any canto, not published)'}`);
  }
  fs.writeFileSync(DATA, `${JSON.stringify(data, null, 1)}\n`);
  process.exit(0);
}

const draft = valueOf('--file');
const plans = draft ? readJson(path.resolve(draft)) : data.cantos;
const only = valueOf('--only')?.split(',');
const clock = t => `${Math.floor(t / 60)}:${String(Math.floor(t % 60)).padStart(2, '0')}`;
let failed = 0;
let beds = 0;
let cues = 0;

for (const [key, plan] of Object.entries(plans)) {
  if (only && !only.includes(key)) continue;
  const [cantica, n] = key.split(':');
  const timingFile = path.join(ROOT, 'public', 'audio-timings', cantica, `${n}.json`);
  if (!fs.existsSync(timingFile)) {
    console.log(`FAIL ${key}: no word timings`);
    failed++;
    continue;
  }
  const timing = readJson(timingFile);
  const placed = resolvePlan(plan, timing, data.sounds);
  const problems = [...placed.problems];
  if (!placed.beds.length || placed.beds[0].t > 0) problems.push('the first entry must be a background (or null) with no "at"');
  placed.beds.forEach((bed, i) => {
    const end = placed.beds[i + 1]?.t ?? timing.totalDuration;
    if (bed.sound && end - bed.t < SHORT_BED) problems.push(`background ${bed.sound} at ${clock(bed.t)} lasts only ${Math.round(end - bed.t)} s`);
  });
  beds += placed.beds.filter(b => b.sound).length;
  cues += placed.cues.length;
  if (problems.length) {
    failed++;
    console.log(`FAIL ${key}\n${problems.map(p => `   ${p}`).join('\n')}`);
  }
  if (only || draft) {
    const line = [...placed.beds.map(b => ({ ...b, kind: 'background' })), ...placed.cues.map(c => ({ ...c, kind: 'cue' }))]
      .sort((a, b) => a.t - b.t)
      .map(e => `${clock(e.t)} ${e.kind === 'cue' ? `(${e.sound})` : e.sound ?? 'silence'}`);
    console.log(`${key} [${clock(timing.totalDuration)}]: ${line.join(', ')}`);
  }
}

const missing = draft || only ? [] : ['inferno', 'purgatorio', 'paradiso'].flatMap(c =>
  fs.readdirSync(path.join(ROOT, 'public', 'audio-timings', c)).map(f => `${c}:${f.replace('.json', '')}`).filter(k => !plans[k]));
if (missing.length) console.log(`No plan (these play with the voice alone): ${missing.join(', ')}`);
console.log(`${Object.keys(plans).length} plans, ${beds} backgrounds, ${cues} cues, ${failed} with problems.`);
process.exit(failed ? 1 : 0);
